def comentarios():
    # Este é um comentário de linha, usado para comentar uma única linha
    """
    Este é um comentário de bloco, pode ser usado para comentar várias linhas
    """
    '''
    Docstring: usada para documentar funções, classes ou módulos, e pode ser
    acessada através do atributo especial __doc__
    '''
    print("Comentários adicionados ao código!")


if __name__ == "__main__":
    comentarios()


# Explicação:
# Este exercício demonstra o uso de três tipos de comentários em Python:
#
# Comentário de linha (#): usado para adicionar anotações em uma única linha.
#
# Comentário de bloco (três aspas duplas ou três aspas simples): utilizado para
# comentar múltiplas linhas de código.
#
# Docstring (três aspas duplas ou três aspas simples): utilizada para documentar
# funções, classes ou módulos. As docstrings são acessíveis durante a execução
# do programa por meio do atributo especial __doc__.
